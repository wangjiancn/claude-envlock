"""Runtime configuration stored in <root>/config.json (generated from claude.env by the installer)."""
import ipaddress
import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, Tuple
from zoneinfo import ZoneInfo

from .common import (ACTIVE_FLAG, CHINA_TIMEZONES, DEFAULT_CHROME, DEFAULT_TIMEZONE, LOOPBACK, NO_PROXY_VALUE,
                     NO_PROXY_VARS, PRIVACY_VARS, PROXY_VARS, SOCKS_VARS, ZONE_TAB)

CONFIG_VERSION = 3
MISMATCH_POLICIES = ('prompt', 'block')
# Keys claude-envlock generates itself. Users can't set them as extra variables.
RESERVED_ENV = frozenset(PROXY_VARS + NO_PROXY_VARS + SOCKS_VARS + tuple(PRIVACY_VARS)
                         + ('BROWSER', 'TZ', 'PATH', ACTIVE_FLAG))
ENV_NAME = re.compile(r'[A-Za-z_][A-Za-z0-9_]*\Z')
# Values must be safe inside double quotes when claude.env is `source`d by a shell.
UNSAFE_VALUE = re.compile(r'["\\$`\r\n]')


def validate_timezone(name):
    if not name:
        raise ValueError('A timezone is required (default: {}).'.format(DEFAULT_TIMEZONE))
    if name in CHINA_TIMEZONES:
        raise ValueError('China timezones are not allowed: {}. Use --timezone with another zone.'.format(name))
    try:
        ZoneInfo(name)
    except (KeyError, ValueError) as exc:  # ZoneInfoNotFoundError is a KeyError
        raise ValueError('Unknown IANA timezone: {!r}'.format(name)) from exc
    return name


def country_timezones(country, zone_tab=ZONE_TAB):
    """Canonical zones for a two-letter country code, from the system's zone.tab. Empty if unknown."""
    zones = []
    for line in Path(zone_tab).read_text().splitlines():
        fields = line.split('\t')
        if len(fields) >= 3 and fields[0] == country.upper():
            zones.append(fields[2])
    return zones


def validate_networks(items):
    for item in items:
        try:
            ipaddress.ip_network(item, strict=False)
        except ValueError as exc:
            raise ValueError('Invalid exit IP or CIDR range: {!r}'.format(item)) from exc
    return tuple(items)


def validate_extra_env(extra):
    for key, value in extra.items():
        if not ENV_NAME.match(key) or key.startswith('CLAUDE_ENVLOCK_'):
            raise ValueError('Invalid variable name: {!r}'.format(key))
        if key in RESERVED_ENV:
            raise ValueError('{} is generated by claude-envlock and cannot be set directly.'.format(key))
        if not isinstance(value, str) or UNSAFE_VALUE.search(value):
            raise ValueError('Value of {} must not contain quotes, backslashes, $, backticks, or newlines.'
                             .format(key))
    return extra


@dataclass(frozen=True)
class Config:
    root: Path
    port: int
    host: str = LOOPBACK
    timeout: float = 5.0
    cli_timezone: str = DEFAULT_TIMEZONE
    allowed_exit_ips: Tuple[str, ...] = ()
    on_mismatch: str = 'prompt'
    extra_env: Dict[str, str] = field(default_factory=dict)
    cli_candidates: Tuple[str, ...] = ()
    cli_variants: Dict[str, str] = field(default_factory=dict)
    chrome: str = DEFAULT_CHROME

    def __post_init__(self):
        if self.host != LOOPBACK:
            raise ValueError('The proxy must listen on {} (local only).'.format(LOOPBACK))
        if isinstance(self.port, bool) or not isinstance(self.port, int) or not 1 <= self.port <= 65535:
            raise ValueError('Proxy port must be an integer between 1 and 65535.')
        validate_timezone(self.cli_timezone)
        if self.on_mismatch not in MISMATCH_POLICIES:
            raise ValueError('CLAUDE_ENVLOCK_ON_MISMATCH must be "prompt" or "block".')
        validate_networks(self.allowed_exit_ips)
        validate_extra_env(self.extra_env)

    @property
    def proxy_url(self):
        return 'http://{}:{}'.format(self.host, self.port)

    @property
    def bin_dir(self):
        return self.root / 'bin'

    @property
    def chrome_profile(self):
        return self.root / 'chrome-profile'

    def managed_env(self):
        """Env written to Claude settings and VS Code. Everything is derived from this config."""
        env = {key: self.proxy_url for key in PROXY_VARS}
        env.update({key: NO_PROXY_VALUE for key in NO_PROXY_VARS})
        env.update({key: '' for key in SOCKS_VARS})
        env.update(PRIVACY_VARS)
        env['BROWSER'] = str(self.bin_dir / 'claude-web')
        env.update(self.extra_env)
        env['TZ'] = self.cli_timezone
        return env

    def exit_ip_allowed(self, ip):
        address = ipaddress.ip_address(ip)
        return any(address in ipaddress.ip_network(net, strict=False) for net in self.allowed_exit_ips)

    @classmethod
    def load(cls, root):
        root = Path(root)
        data = json.loads((root / 'config.json').read_text())
        return cls(
            root=root,
            port=data['port'],
            host=data.get('host', LOOPBACK),
            timeout=data.get('timeout', 5.0),
            cli_timezone=data.get('cli_timezone') or DEFAULT_TIMEZONE,
            allowed_exit_ips=tuple(data.get('allowed_exit_ips', ())),
            on_mismatch=data.get('on_mismatch', 'prompt'),
            extra_env=dict(data.get('extra_env', {})),
            cli_candidates=tuple(data.get('cli_candidates', ())),
            cli_variants=dict(data.get('cli_variants', {})),
            chrome=data.get('chrome', DEFAULT_CHROME),
        )

    def to_json(self):
        data = {
            'version': CONFIG_VERSION,
            'host': self.host,
            'port': self.port,
            'timeout': self.timeout,
            'cli_timezone': self.cli_timezone,
            'allowed_exit_ips': list(self.allowed_exit_ips),
            'on_mismatch': self.on_mismatch,
            'extra_env': self.extra_env,
            'cli_candidates': list(self.cli_candidates),
            'cli_variants': self.cli_variants,
            'chrome': self.chrome,
        }
        return json.dumps(data, indent=2, ensure_ascii=False) + '\n'
