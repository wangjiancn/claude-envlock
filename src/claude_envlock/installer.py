"""Transactional, idempotent installer.

Never edits proxy nodes, the system proxy, the system timezone, or the default browser.
Every file it touches is recorded (with the original bytes) in <root>/backups/manifest.json,
so `claude-rollback` can restore it exactly.
"""
import argparse
import base64
import json
import os
from pathlib import Path
import plistlib
import sys

from . import __version__
from . import envfile
from .common import (APP_NAME, DEFAULT_CHROME, DEFAULT_PORT, LAUNCHERS, SHELL_BEGIN, SHELL_END, SHELL_FILES,
                     atomic_write, default_root, manifest_path, render_shell_block, sha256)
from .config import Config
from .jsonc import loads, update

PACKAGE_DIR = Path(__file__).resolve().parent
# Only these modules are deployed; the installer itself and jsonc stay in the repo.
RUNTIME_MODULES = ('__init__.py', 'common.py', 'config.py', 'proxy.py', 'launchers.py', 'cli.py',
                   'integrity.py', 'prompt.py', 'jsonc.py', 'rollback.py')
SHIM = '''#!/usr/bin/python3 -IB
"""claude-envlock launcher. Generated by the installer; do not edit."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'lib'))
from claude_envlock.cli import main  # noqa: E402

sys.exit(main(ROOT, sys.argv))
'''


# Markers written by releases before the rename to claude-envlock. Upgrades replace them in place.
LEGACY_SHELL_MARKERS = (('# >>> Claude Safe managed entry >>>', '# <<< Claude Safe managed entry <<<'),)


# ---------------------------------------------------------------- pure helpers

def shell_block(text, block):
    """Insert or replace the single managed block (current or legacy markers) in a shell rc file."""
    for begin, end in ((SHELL_BEGIN, SHELL_END),) + LEGACY_SHELL_MARKERS:
        if begin in text or end in text:
            if text.count(begin) != 1 or text.count(end) != 1 or text.index(begin) > text.index(end):
                raise ValueError('Malformed claude-envlock markers in shell config; stopping to avoid damage.')
            start, stop = text.index(begin), text.index(end) + len(end)
            return text[:start] + block + text[stop:]
    return text + ('' if not text or text.endswith('\n') else '\n') + '\n' + block + '\n'


def default_cli_paths(home):
    homebrew = ['/opt/homebrew/bin/claude', '/usr/local/bin/claude']
    native = str(Path(home) / '.local' / 'bin' / 'claude')
    return homebrew, native


def discover_cli(explicit, home, root):
    """Return (candidates, variants). Fails if no original Claude CLI is installed."""
    if explicit:
        candidates, variants = [str(Path(p).expanduser().absolute()) for p in explicit], {}
    else:
        homebrew, native = default_cli_paths(home)
        npm = next((p for p in homebrew if Path(p).is_file()), homebrew[0])
        candidates, variants = homebrew + [native], {'npm': npm, 'native': native}
    root = Path(root).resolve()
    usable = [p for p in candidates if Path(p).is_file() and os.access(p, os.X_OK)
              and root not in Path(p).resolve().parents]
    if not usable:
        raise RuntimeError('No Claude CLI found. Install Claude Code first, or pass --claude /path/to/claude.')
    return candidates, variants


def rebase_settings_backup(record, current, previous_env):
    """Adopt unrelated edits into the rollback backup; refuse if managed env keys were changed."""
    original = json.loads(base64.b64decode(record['original'])) if record['existed'] else {}
    if not isinstance(current.get('env', {}), dict):
        raise ValueError('Claude settings "env" is not an object.')
    for key, expected in previous_env.items():
        if current.get('env', {}).get(key) != expected:
            raise RuntimeError('Managed Claude env var was edited by hand; refusing to merge: ' + key)
    restored = dict(current)
    restored_env = dict(current.get('env', {}))
    original_env = original.get('env', {})
    for key in previous_env:
        if key in original_env:
            restored_env[key] = original_env[key]
        else:
            restored_env.pop(key, None)
    if restored_env or 'env' in original:
        restored['env'] = restored_env
    else:
        restored.pop('env', None)
    record['existed'] = True
    record['original'] = base64.b64encode(
        (json.dumps(restored, ensure_ascii=False, indent=2) + '\n').encode()).decode()


# ---------------------------------------------------------------- transaction

class Plan:
    """Collects desired file contents, then applies them all-or-nothing."""

    def __init__(self, root, merge_unmanaged=False):
        self.root = Path(root)
        self.manifest_file = manifest_path(root)
        self.previous = (json.loads(self.manifest_file.read_text()) if self.manifest_file.exists()
                         else {'version': 1, 'files': {}})
        self.manifest = json.loads(json.dumps(self.previous))
        self.merge_unmanaged = merge_unmanaged
        self.changes = {}
        self.desired = set()
        self.removals = []

    def owns(self, prefix):
        return any(name.startswith(str(prefix) + '/') for name in self.manifest['files'])

    def stage(self, path, content, mode=0o600, merge_env=None, user_editable=False):
        if isinstance(content, str):
            content = content.encode()
        path = Path(path)
        self.desired.add(str(path))
        if path.is_symlink():
            raise RuntimeError('Refusing to replace a symlink: {}'.format(path))
        exists = path.exists()
        old = path.read_bytes() if exists else None
        record = self.manifest['files'].get(str(path))
        adopted = False
        if record and not user_editable and (old is None or sha256(old) != record['installed_sha256']):
            if old is not None and merge_env is not None and self.merge_unmanaged:
                rebase_settings_backup(record, json.loads(old), merge_env)
                adopted = True
                print('Keeping unmanaged Claude settings and updating the rollback backup.')
            else:
                raise RuntimeError('File changed after deployment; resolve the conflict first: {}'.format(path))
        recorded_ok = record is None or record['installed_sha256'] == sha256(content)
        if not adopted and recorded_ok and old == content and (path.stat().st_mode & 0o777) == mode:
            return
        self.changes[str(path)] = (content, mode)
        if not record:
            record = {'existed': exists,
                      'original': base64.b64encode(old).decode() if exists else None,
                      'mode': (path.stat().st_mode & 0o777) if exists else None}
            self.manifest['files'][str(path)] = record
        record['installed_sha256'] = sha256(content)

    def retire_stale(self, folders):
        """Remove files we created earlier that this version no longer installs (e.g. a renamed app)."""
        prefixes = tuple(str(f) + '/' for f in folders)
        for name, record in list(self.manifest['files'].items()):
            if name in self.desired or not name.startswith(prefixes) or record['existed']:
                continue
            path = Path(name)
            if path.exists() and (path.is_symlink() or sha256(path.read_bytes()) != record['installed_sha256']):
                raise RuntimeError('File changed after deployment; resolve the conflict first: {}'.format(path))
            del self.manifest['files'][name]
            if path.exists():
                self.removals.append(name)

    def prepare_dirs(self):
        for folder in (self.root, self.root / 'bin', self.root / 'backups', self.root / 'chrome-profile'):
            folder.mkdir(mode=0o700, exist_ok=True)
            os.chmod(str(folder), 0o700)

    @property
    def pending(self):
        return len(self.changes) + len(self.removals)

    def apply(self):
        snapshots = {p: (Path(p).read_bytes(), Path(p).stat().st_mode & 0o777) if Path(p).exists() else None
                     for p in list(self.changes) + self.removals}
        # Persist recoverable originals before touching any managed file.
        atomic_write(self.manifest_file, (json.dumps(self.manifest, indent=2) + '\n').encode(), 0o600)
        try:
            for path, (content, mode) in self.changes.items():
                atomic_write(Path(path), content, mode)
            for path in self.removals:
                Path(path).unlink()
        except Exception:
            for path, value in snapshots.items():
                if value is None:
                    Path(path).unlink(missing_ok=True)
                else:
                    atomic_write(Path(path), value[0], value[1])
            atomic_write(self.manifest_file, (json.dumps(self.previous, indent=2) + '\n').encode(), 0o600)
            raise
        for path in self.removals:  # tidy up now-empty bundle folders (e.g. an old .app)
            for folder in Path(path).parents:
                if folder == self.root or folder == folder.parent:
                    break
                try:
                    folder.rmdir()
                except OSError:
                    break


# ---------------------------------------------------------------- staging steps

def stage_runtime(plan, root):
    for module in RUNTIME_MODULES:
        plan.stage(root / 'lib' / 'claude_envlock' / module, (PACKAGE_DIR / module).read_bytes(), 0o600)
    for name in LAUNCHERS:
        plan.stage(root / 'bin' / name, SHIM, 0o700)


def stage_claude_settings(plan, home, env, previous_env, stale_keys):
    path = home / '.claude' / 'settings.json'
    data = json.loads(path.read_text()) if path.exists() else {}
    if not isinstance(data, dict) or not isinstance(data.get('env', {}), dict):
        raise ValueError('{} is not a valid settings object; not overwriting it.'.format(path))
    data.setdefault('env', {})
    for key in stale_keys:
        if data['env'].get(key) == previous_env.get(key):
            data['env'].pop(key, None)
    data['env'].update(env)
    plan.stage(path, json.dumps(data, ensure_ascii=False, indent=2) + '\n', merge_env=previous_env)


def stage_vscode_settings(plan, home, root, env, stale_keys):
    path = home / 'Library' / 'Application Support' / 'Code' / 'User' / 'settings.json'
    text = path.read_text() if path.exists() else '{}\n'
    data = loads(text)
    variables = data.get('claudeCode.environmentVariables', [])
    if not isinstance(variables, list) or any(not isinstance(x, dict) or 'name' not in x for x in variables):
        raise ValueError('VS Code "claudeCode.environmentVariables" has an unexpected format.')
    names = set(env) | set(stale_keys)
    variables = [x for x in variables if x['name'] not in names] + [{'name': k, 'value': v} for k, v in env.items()]
    changes = {'claudeCode.claudeProcessWrapper': str(root / 'bin' / 'claude-ide-wrapper'),
               'claudeCode.environmentVariables': variables}
    new_text = update(text, changes)
    expected = dict(data)
    expected.update(changes)
    if loads(new_text) != expected:
        raise ValueError('VS Code JSONC edit failed verification; nothing written.')
    plan.stage(path, new_text)


def stage_shell(plan, home):
    for name in SHELL_FILES:
        path = home / name
        text = path.read_text() if path.exists() else ''
        mode = path.stat().st_mode & 0o777 if path.exists() else 0o600
        plan.stage(path, shell_block(text, render_shell_block(name)), mode)


def stage_app(plan, app):
    if app.exists() and not plan.owns(app):
        raise RuntimeError('{} already exists and was not created by claude-envlock; stopping.'.format(app))
    plan.manifest['app_dir'] = str(app)
    info = {'CFBundleName': APP_NAME, 'CFBundleDisplayName': APP_NAME,
            'CFBundleIdentifier': 'local.claude-envlock.launcher', 'CFBundleVersion': __version__,
            'CFBundleShortVersionString': __version__, 'CFBundlePackageType': 'APPL',
            'CFBundleExecutable': APP_NAME, 'LSUIElement': True, 'NSHighResolutionCapable': True}
    plan.stage(app / 'Contents' / 'Info.plist', plistlib.dumps(info), 0o644)
    plan.stage(app / 'Contents' / 'MacOS' / APP_NAME,
               '#!/bin/zsh\nexec "$HOME/.claude-env/bin/claude-web" "https://claude.ai/"\n', 0o755)


# ---------------------------------------------------------------- main

def parse_args(argv=None):
    ap = argparse.ArgumentParser(prog='install.sh', description='Install, upgrade, or apply claude.env. '
                                 'Flags edit ~/.claude-env/claude.env; omitted values keep what it already says.')
    ap.add_argument('--port', type=int, help='local HTTP proxy port (first install default: {})'.format(DEFAULT_PORT))
    tz = ap.add_mutually_exclusive_group()
    tz.add_argument('--timezone', help='IANA timezone for Claude CLI / IDE processes only')
    tz.add_argument('--no-timezone', action='store_true', help='stop overriding TZ for Claude processes')
    ap.add_argument('--exit-ips', metavar='"IP CIDR ..."',
                    help='replace the exit-IP allowlist (space-separated; "" turns the check off)')
    ap.add_argument('--on-mismatch', choices=('prompt', 'block'),
                    help='on drift or a disallowed exit IP: Block/Continue popup, or always block')
    ap.add_argument('--claude', action='append', metavar='PATH',
                    help='original Claude CLI to wrap (repeatable; default: auto-detect)')
    ap.add_argument('--chrome', default=DEFAULT_CHROME, help='Google Chrome executable')
    ap.add_argument('--app-dir', default='/Applications/{}.app'.format(APP_NAME), help='where to create the app')
    ap.add_argument('--merge-unmanaged-settings', action='store_true',
                    help='keep settings Claude wrote itself (e.g. "tui"); edits to managed env still fail')
    ap.add_argument('--dry-run', action='store_true', help='report what would change; write nothing')
    ap.add_argument('--version', action='version', version='claude-envlock ' + __version__)
    return ap.parse_args(argv)


def load_previous_config(root):
    try:
        return Config.load(root) if (root / 'config.json').exists() else None
    except (ValueError, KeyError, TypeError):
        return None


def resolve_settings(args, env_path, previous):
    """claude.env is the source; flags edit it; older installs migrate from config.json."""
    values = envfile.parse(env_path.read_text()) if env_path.exists() else None
    if values is not None:
        settings = envfile.settings_from_values(values)
    elif previous:
        settings = envfile.settings_from_config(previous)
    else:
        settings = {'port': DEFAULT_PORT, 'cli_timezone': None, 'allowed_exit_ips': (),
                    'on_mismatch': 'prompt', 'extra_env': {}}
    if args.port is not None:
        settings['port'] = args.port
    if args.timezone:
        settings['cli_timezone'] = args.timezone
    if args.no_timezone:
        settings['cli_timezone'] = None
    if args.exit_ips is not None:
        settings['allowed_exit_ips'] = tuple(args.exit_ips.replace(',', ' ').split())
    if args.on_mismatch:
        settings['on_mismatch'] = args.on_mismatch
    return settings, values


def run(args, home=None, root=None):
    home = Path(home or Path.home())
    root = Path(root or default_root())
    previous = load_previous_config(root)
    env_path = root / envfile.FILENAME
    settings, values = resolve_settings(args, env_path, previous)
    candidates, variants = discover_cli(args.claude, home, root)
    cfg = Config(root=root, cli_candidates=tuple(candidates), cli_variants=variants, chrome=args.chrome, **settings)

    env = cfg.managed_env()
    previous_env = previous.managed_env() if previous else {}
    if values is not None:
        edited = envfile.hand_edited_generated_keys(values, previous_env, env)
        if edited:
            raise ValueError('Generated line(s) edited by hand in claude.env: {}. Change the CLAUDE_ENVLOCK_* '
                             'settings instead (or delete those lines).'.format(', '.join(edited)))
    if previous and previous.port != cfg.port:
        lock = cfg.chrome_profile / 'SingletonLock'
        if lock.exists() or lock.is_symlink():
            raise RuntimeError('Quit the dedicated Chrome before changing the port (it would keep the old proxy).')
    stale_keys = sorted(set(previous_env) - set(env))

    plan = Plan(root, merge_unmanaged=args.merge_unmanaged_settings)
    plan.stage(env_path, envfile.render(cfg), user_editable=True)
    plan.stage(root / 'config.json', cfg.to_json())
    stage_runtime(plan, root)
    stage_claude_settings(plan, home, env, previous_env, stale_keys)
    stage_vscode_settings(plan, home, root, env, stale_keys)
    stage_shell(plan, home)
    stage_app(plan, Path(args.app_dir).expanduser().absolute())
    old_app = plan.previous.get('app_dir')
    plan.retire_stale([root / 'bin', root / 'lib'] + ([Path(old_app)] if old_app and old_app != plan.manifest['app_dir'] else []))

    print('Source of truth: {}'.format(env_path))
    print('Proxy: {} (nodes and system proxy unchanged)'.format(cfg.proxy_url))
    print('Claude timezone: {}'.format(cfg.cli_timezone or 'system (not overridden)'))
    print('Exit-IP allowlist: {}'.format(' '.join(cfg.allowed_exit_ips) or 'off'))
    print('On mismatch: {}'.format(cfg.on_mismatch))
    if cfg.extra_env:
        print('Extra variables: {}'.format(', '.join(sorted(cfg.extra_env))))
    print('Files to update: {}'.format(plan.pending))
    if args.dry_run:
        return 0
    plan.prepare_dirs()
    if not plan.pending:
        print('Already up to date; nothing to change.')
        return 0
    plan.apply()
    print('Done. Open a new terminal, and run "Developer: Reload Window" in VS Code.')
    return 0


def main(argv=None):
    try:
        return run(parse_args(argv))
    except Exception as exc:
        print('Install failed: {}'.format(exc), file=sys.stderr)
        return 1
